"""Settings precedence in the Proton wrapper: global < per-game JSON < per-game
.env, and a value the user exported always beats all of them. A stale copy of a
GreenBoost setting left by the old environment.d file must NOT beat a saved
change. The wrapper runs main() at import, so the helpers are lifted with ast."""
from __future__ import annotations

import ast
import os
from pathlib import Path

import pytest

WRAPPER = Path(__file__).resolve().parent.parent / "greenboost_proton" / "gb_proton_main.py"
WANTED = {"_GB_OWNED", "_GB_STALE_ENVD", "_stale_envd", "_gb_setenv", "_apply_per_game_env"}


@pytest.fixture()
def ns(tmp_path, monkeypatch):
    src = WRAPPER.read_text(encoding="utf-8")
    lines = src.splitlines(True)
    chunks = []
    for node in ast.parse(src).body:
        name = getattr(node, "name", None)
        if name is None and isinstance(node, ast.Assign):
            name = getattr(node.targets[0], "id", None)
        if name in WANTED:
            chunks.append("".join(lines[node.lineno - 1:node.end_lineno]))
    scope = {"os": os, "sys": __import__("sys")}
    exec("\n".join(chunks), scope)
    monkeypatch.setenv("HOME", str(tmp_path))
    for k in ("GB_T_A", "GB_T_B", "GB_T_USER"):
        monkeypatch.delenv(k, raising=False)
    return scope


def write_stale(tmp_path, body, header=True):
    d = tmp_path / ".config" / "environment.d"
    d.mkdir(parents=True)
    (d / "greenboost.conf").write_text(
        ("# Generated by GreenBoost Gaming Suite , do not edit manually\n" if header else "# mine\n") + body)


def test_higher_layer_overrides_lower_one(ns):
    ns["_gb_setenv"]("GB_T_A", "global")
    ns["_gb_setenv"]("GB_T_A", "per-game")
    assert os.environ["GB_T_A"] == "per-game"


def test_users_own_export_beats_every_layer(ns, monkeypatch):
    monkeypatch.setenv("GB_T_USER", "from launch options")
    ns["_gb_setenv"]("GB_T_USER", "global")
    ns["_gb_setenv"]("GB_T_USER", "per-game")
    assert os.environ["GB_T_USER"] == "from launch options"


def test_stale_environment_d_value_is_overridden(ns, tmp_path, monkeypatch):
    write_stale(tmp_path, "GB_T_A=old-saved\n")
    monkeypatch.setenv("GB_T_A", "old-saved")            # what Steam inherited at login
    ns["_gb_setenv"]("GB_T_A", "new-saved")
    assert os.environ["GB_T_A"] == "new-saved"


def test_a_different_user_value_is_not_mistaken_for_stale(ns, tmp_path, monkeypatch):
    write_stale(tmp_path, "GB_T_A=old-saved\n")
    monkeypatch.setenv("GB_T_A", "user typed this")      # differs from the stale file
    ns["_gb_setenv"]("GB_T_A", "new-saved")
    assert os.environ["GB_T_A"] == "user typed this"


def test_someone_elses_environment_d_file_is_ignored(ns, tmp_path, monkeypatch):
    write_stale(tmp_path, "GB_T_A=theirs\n", header=False)
    monkeypatch.setenv("GB_T_A", "theirs")
    ns["_gb_setenv"]("GB_T_A", "saved")
    assert os.environ["GB_T_A"] == "theirs"


def test_per_game_env_file_overrides_global(ns, tmp_path):
    ns["_gb_setenv"]("GB_T_B", "global")
    d = tmp_path / ".config" / "greenboost-gaming" / "per-game"
    d.mkdir(parents=True)
    (d / "42.env").write_text("GB_T_B=per-game-env\n")
    ns["_apply_per_game_env"]("42")
    assert os.environ["GB_T_B"] == "per-game-env"
